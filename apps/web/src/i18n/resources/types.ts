import type { ru } from "./ru"

// `ru` объявлен `as const`, поэтому `typeof ru` — это структура из строковых
// ЛИТЕРАЛОВ («Вывод», «Источники»). Прямое `satisfies typeof ru` потребовало бы
// от казахского ресурса тех же самых русских строк, то есть запретило бы
// перевод. Widen рекурсивно расширяет литералы до `string`, оставляя ключи
// нетронутыми: локаль обязана повторить СОСТАВ ключей, но свободна в тексте.
type Widen<T> = T extends string ? string : { [K in keyof T]: Widen<T[K]> }

/**
 * Контракт ресурса локали. Пропущенный ключ и опечатка в ключе падают на
 * `tsc -b` — это и есть замена тестам для переводов (тестового раннера
 * в apps/web нет, вопрос 15 к Full-stack 1 открыт).
 */
export type TranslationResource = Widen<typeof ru>
