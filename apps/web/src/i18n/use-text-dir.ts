import { isRtl } from "./config"
import { useLocale } from "./use-locale"

/**
 * Направление ТЕКСТА хрома. Макет остаётся LTR (решение владельца продукта
 * 06.08.2026): лента слева, карта в центре, шкала реплея слева направо —
 * хронология доказательств и течение реки не зеркалятся.
 *
 * Ставится только на листовые элементы с прозой (<p>, <h2>, <li>), где нет
 * горизонтальной раскладки: dir на контейнере с flex-детьми перевернул бы
 * их порядок. Текст ДАННЫХ получает dir="auto" — он может оказаться
 * непереведённым русским оригиналом даже в персидском интерфейсе.
 */
export function useTextDir(): "rtl" | "ltr" {
  const { locale } = useLocale()
  return isRtl(locale) ? "rtl" : "ltr"
}
